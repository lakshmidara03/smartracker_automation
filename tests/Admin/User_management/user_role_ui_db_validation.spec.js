/**
 * User & Role Management: UI-to-Database Parity & Lifecycle Validation Suite
 * 
 * Validates UI screens, table records, role dropdowns, and role changes
 * directly against MySQL database tables:
 * - `user`
 * - `role`
 * - `user_role`
 * 
 * Catalog:
 * - Suite 1: Database Schema & UI Parity Validation (UIDB-01 to UIDB-05)
 * - Suite 2: UI Actions & Direct Database Lifecycle Validation (UIDB-06 to UIDB-10)
 */

const { test, expect } = require('@playwright/test');
const mysql = require('mysql2/promise');
const path = require('path');
require('dotenv').config({ path: path.resolve(__dirname, '../../../.env') });

// Turn off trace recording to avoid Windows file-lock issues
test.use({ trace: 'off' });

// ============================================================
// CONFIGURATION & DATABASE HELPERS
// ============================================================
const BASE_URL = (process.env.UI_BASE_URL || 'http://localhost:4200').replace(/\/$/, '');
const UPDATE_ROLE_URL = `${BASE_URL}/admin/update-role`;

let dbConnection = null;

async function getDbConnection() {
    if (!dbConnection) {
        const isLocal = BASE_URL.includes('localhost') || BASE_URL.includes('127.0.0.1');
        try {
            dbConnection = await mysql.createConnection({
                host: isLocal ? 'localhost' : (process.env.DB_HOST || '13.61.179.149'),
                port: parseInt(process.env.DB_PORT || '3306', 10),
                user: process.env.DB_USER || 'root',
                password: isLocal ? (process.env.LOCAL_DB_PASSWORD || 'root') : (process.env.DB_PASSWORD || 'relanto123'),
                database: process.env.DB_NAME || 'hrportal'
            });
        } catch {
            dbConnection = await mysql.createConnection({
                host: process.env.DB_HOST || '13.61.179.149',
                port: parseInt(process.env.DB_PORT || '3306', 10),
                user: process.env.DB_USER || 'root',
                password: process.env.DB_PASSWORD || 'relanto123',
                database: process.env.DB_NAME || 'hrportal'
            });
        }
    }
    return dbConnection;
}

test.afterAll(async () => {
    if (dbConnection) {
        await dbConnection.end().catch(() => {});
        dbConnection = null;
    }
});

// ============================================================
// PAGE HELPERS & LOCATORS
// ============================================================
const usersTab = (page) =>
    page.getByRole('button', { name: /users\s*&\s*roles/i });

const updateTab = (page) =>
    page.getByRole('button', { name: /^update role$/i }).first();

const userSearch = (page) =>
    page.getByPlaceholder('Search users...', { exact: true });

const employeeSearch = (page) =>
    page.getByPlaceholder('Search employee by name...', { exact: true });

const userRows = (page) =>
    page.locator('table tbody tr:not(:has(td.empty))');

const roleFilter = (page) =>
    page.locator('select').filter({
        has: page.locator('option', { hasText: /All roles/i })
    }).first();

const assignmentRole = (page) =>
    page.locator('select').filter({
        has: page.locator('option', { hasText: /Select a Role/i })
    }).first();

const updateButton = (page) =>
    page.getByRole('button', { name: /^update role$/i }).last();

const openUsersTab = async (page) => {
    await usersTab(page).click();
    await expect(userSearch(page)).toBeVisible();
    await expect(roleFilter(page)).toBeVisible();
};

const openUpdateTab = async (page) => {
    await updateTab(page).click();
    await page.waitForLoadState('networkidle').catch(() => {});
    await expect(employeeSearch(page)).toBeVisible();
    await expect(assignmentRole(page)).toBeVisible();
};

const chooseFilter = async (page, role) => {
    const filter = roleFilter(page);
    await filter.selectOption({ label: role });
    await page.waitForTimeout(300);
};

// ============================================================
// SUITE 1: DATABASE SCHEMA & UI PARITY VALIDATION
// ============================================================
test.describe('Suite 1: Database Schema & UI Parity Validation', () => {

    test.beforeEach(async ({ page }) => {
        await page.goto(UPDATE_ROLE_URL, {
            waitUntil: 'domcontentloaded',
            timeout: 60000
        });
        await expect(page.getByText('Update Role', { exact: true }).first()).toBeVisible({ timeout: 30000 });
    });

    test('UIDB-01: Verify physical table names in MySQL schema', async () => {
        const conn = await getDbConnection();
        const [tables] = await conn.query('SHOW TABLES');
        const tableNames = tables.map(t => Object.values(t)[0].toLowerCase());

        // Confirm User table is 'user' (physical table generated by Hibernate)
        expect(tableNames).toContain('user');

        // Confirm Role table is 'role'
        expect(tableNames).toContain('role');

        // Confirm USER_ROLE mapping table is 'user_role'
        expect(tableNames).toContain('user_role');

        // Verify column definitions for 'user' table
        const [userCols] = await conn.query('DESCRIBE user');
        const userColNames = userCols.map(c => c.Field.toLowerCase());
        expect(userColNames).toContain('user_name');
        expect(userColNames).toContain('user_first_name');
        expect(userColNames).toContain('user_last_name');
        expect(userColNames).toContain('user_password');

        // Verify column definitions for 'user_role' table
        const [urCols] = await conn.query('DESCRIBE user_role');
        const urColNames = urCols.map(c => c.Field.toLowerCase());
        expect(urColNames).toContain('user_name');
        expect(urColNames).toContain('role_name');
    });

    test('UIDB-02: Validate UI Users count matches MySQL total users', async ({ page }) => {
        await openUsersTab(page);

        // Direct SQL count of registered users
        const conn = await getDbConnection();
        const [totUsers] = await conn.query('SELECT COUNT(*) as cnt FROM user');
        const dbTotal = totUsers[0].cnt;

        // UI Tab header includes count, e.g. "Users & Roles (61)"
        const tabBtnText = await usersTab(page).innerText();
        const countMatch = tabBtnText.match(/\((\d+)\)/);
        expect(countMatch).not.toBeNull();
        const uiTotal = parseInt(countMatch[1], 10);

        expect(uiTotal, `UI user count (${uiTotal}) must equal DB count (${dbTotal})`).toBe(dbTotal);
    });

    test('UIDB-03: Validate UI user table records against MySQL user & user_role data', async ({ page }) => {
        await openUsersTab(page);

        const conn = await getDbConnection();
        // Fetch top 5 users alphabetically from DB
        const [dbUsers] = await conn.query(`
            SELECT 
                u.user_name,
                u.user_first_name,
                u.user_last_name,
                COALESCE(ur.ROLE_NAME, 'No Role') AS role_name
            FROM user u
            LEFT JOIN user_role ur ON ur.USER_NAME = u.user_name
            ORDER BY u.user_first_name ASC, u.user_last_name ASC
            LIMIT 5
        `);

        for (const dbUser of dbUsers) {
            const fullName = `${dbUser.user_first_name || ''} ${dbUser.user_last_name || ''}`.trim();
            if (!fullName) continue;

            // Search by username / email in UI
            await userSearch(page).fill(dbUser.user_name);
            await page.waitForTimeout(300);

            const row = userRows(page).filter({ hasText: dbUser.user_name });
            await expect(row).toHaveCount(1);

            // Validate columns in row
            const uiName = (await row.locator('td').nth(0).innerText()).trim();
            const uiEmail = (await row.locator('td').nth(1).innerText()).trim();
            const uiRole = (await row.locator('td').nth(2).innerText()).trim();

            expect(uiEmail).toBe(dbUser.user_name);
            expect(uiName).toContain(dbUser.user_first_name);
            expect(uiRole).toBe(dbUser.role_name);
        }
    });

    test('UIDB-04: Validate UI Role dropdown options against MySQL role table', async ({ page }) => {
        await openUpdateTab(page);

        const conn = await getDbConnection();
        const [dbRoles] = await conn.query('SELECT role_name FROM role');
        const dbRoleNames = dbRoles.map(r => r.role_name);

        const selectOptions = (
            await assignmentRole(page).locator('option').allTextContents()
        ).map(o => o.trim()).filter(o => o && !o.includes('-- Select a Role --'));

        // Verify that every selectable role in the UI exists in MySQL role table (with known UI abbreviation OPS -> Operation team)
        for (const uiRole of selectOptions) {
            const matchesDb = dbRoleNames.includes(uiRole) || (uiRole === 'OPS' && dbRoleNames.includes('Operation team'));
            expect(
                matchesDb,
                `UI option "${uiRole}" must exist in MySQL role table (or match Operation team)`
            ).toBeTruthy();
        }
    });

    test('UIDB-05: Password security - passwords encrypted in DB and absent from DOM', async ({ page }) => {
        const conn = await getDbConnection();
        const [users] = await conn.query('SELECT user_name, user_password FROM user LIMIT 10');

        for (const u of users) {
            const pwd = u.user_password;
            expect(pwd).toBeTruthy();
            // Passwords must be hashed/encrypted (not plain text passwords like "password", "123456")
            expect(pwd.length).toBeGreaterThanOrEqual(15);
            expect(pwd).not.toBe('password');
            expect(pwd).not.toBe('admin123');

            // Passwords must NEVER be present anywhere in the DOM HTML
            const pageContent = await page.content();
            expect(pageContent).not.toContain(pwd);
        }
    });
});

// ============================================================
// SUITE 2: UI ACTIONS & DIRECT DATABASE LIFECYCLE VALIDATION
// ============================================================
test.describe('Suite 2: UI Actions & Direct Database Lifecycle Validation', () => {

    test.beforeEach(async ({ page }) => {
        await page.goto(UPDATE_ROLE_URL, {
            waitUntil: 'domcontentloaded',
            timeout: 60000
        });
        await expect(page.getByText('Update Role', { exact: true }).first()).toBeVisible({ timeout: 30000 });
    });

    test('UIDB-06: Filter users by role in UI vs MySQL COUNT query', async ({ page }) => {
        await openUsersTab(page);

        const conn = await getDbConnection();
        const testRoles = ['Admin', 'Practice Lead', 'Super User', 'User', 'TA', 'No Role'];

        for (const role of testRoles) {
            await chooseFilter(page, role);

            let expectedDbCount;
            if (role === 'No Role') {
                const [res] = await conn.query(`
                    SELECT COUNT(*) as cnt 
                    FROM user u 
                    LEFT JOIN user_role ur ON ur.USER_NAME = u.user_name 
                    WHERE ur.ROLE_NAME IS NULL
                `);
                expectedDbCount = res[0].cnt;
            } else {
                const [res] = await conn.query('SELECT COUNT(*) as cnt FROM user_role WHERE ROLE_NAME = ?', [role]);
                expectedDbCount = res[0].cnt;
            }

            const matchingRows = await userRows(page).count();
            if (expectedDbCount === 0) {
                expect(matchingRows).toBe(0);
                await expect(page.locator('td.empty')).toContainText('No users found');
            } else {
                expect(
                    matchingRows,
                    `Role "${role}" row count in UI (${matchingRows}) must equal DB count (${expectedDbCount})`
                ).toBe(expectedDbCount);
            }
        }
    });

    test('UIDB-07: Change role in UI and verify direct MySQL USER_ROLE mapping', async ({ page }) => {
        const testEmployee = 'Yashwanth Sharma';
        const targetUsername = 'yashwanth.sharma@relanto.ai';
        const conn = await getDbConnection();

        // 1. Read current role directly from MySQL
        const [origRows] = await conn.query('SELECT ROLE_NAME FROM user_role WHERE USER_NAME = ?', [targetUsername]);
        expect(origRows.length).toBe(1);
        const originalRole = origRows[0].ROLE_NAME;
        const newRole = originalRole === 'User' ? 'Practice Lead' : 'User';

        try {
            // 2. Perform role update via UI
            await openUpdateTab(page);

            const input = employeeSearch(page);
            await input.click();
            await input.fill('Yashwanth');
            await page.waitForTimeout(300);

            const suggestion = page.locator('#ac div', { hasText: /Yashwanth Sharma/i }).first();
            await expect(suggestion).toBeVisible({ timeout: 10000 });
            await suggestion.click();
            await expect(page.locator('#sel')).toBeVisible();

            await assignmentRole(page).selectOption({ label: newRole });
            await updateButton(page).click();

            // Dismiss modal
            const okBtn = page.locator('button.modal-btn', { hasText: 'OK' });
            await okBtn.waitFor({ state: 'visible', timeout: 5000 });
            await okBtn.click();
            await page.waitForTimeout(500);

            // 3. Directly query MySQL USER_ROLE table
            const [updatedRows] = await conn.query('SELECT ROLE_NAME FROM user_role WHERE USER_NAME = ?', [targetUsername]);
            expect(updatedRows.length, 'User should have exactly 1 role mapping in user_role').toBe(1);
            expect(updatedRows[0].ROLE_NAME, `MySQL user_role mapping must now be "${newRole}"`).toBe(newRole);

        } finally {
            // 4. Restore original role directly via MySQL to guarantee test hygiene
            await conn.query('DELETE FROM user_role WHERE USER_NAME = ?', [targetUsername]);
            await conn.query('INSERT INTO user_role (USER_NAME, ROLE_NAME) VALUES (?, ?)', [targetUsername, originalRole]);

            const [restoredRows] = await conn.query('SELECT ROLE_NAME FROM user_role WHERE USER_NAME = ?', [targetUsername]);
            expect(restoredRows[0].ROLE_NAME).toBe(originalRole);
        }
    });

    test('UIDB-08: Restore role via UI and verify MySQL reflects restoration', async ({ page }) => {
        const testEmployee = 'Yashwanth Sharma';
        const targetUsername = 'yashwanth.sharma@relanto.ai';
        const conn = await getDbConnection();

        const [origRows] = await conn.query('SELECT ROLE_NAME FROM user_role WHERE USER_NAME = ?', [targetUsername]);
        const originalRole = origRows[0].ROLE_NAME;

        // Perform assignment of original role in UI to ensure form submission restores cleanly
        await openUpdateTab(page);

        const input = employeeSearch(page);
        await input.click();
        await input.fill('Yashwanth');
        await page.waitForTimeout(300);

        const suggestion = page.locator('#ac div', { hasText: /Yashwanth Sharma/i }).first();
        await expect(suggestion).toBeVisible({ timeout: 10000 });
        await suggestion.click();
        await expect(page.locator('#sel')).toBeVisible();

        await assignmentRole(page).selectOption({ label: originalRole });
        await updateButton(page).click();

        const okBtn = page.locator('button.modal-btn', { hasText: 'OK' });
        await okBtn.waitFor({ state: 'visible', timeout: 5000 });
        await okBtn.click();
        await page.waitForTimeout(500);

        // Verify in MySQL
        const [dbRows] = await conn.query('SELECT ROLE_NAME FROM user_role WHERE USER_NAME = ?', [targetUsername]);
        expect(dbRows.length).toBe(1);
        expect(dbRows[0].ROLE_NAME).toBe(originalRole);
    });

    test('UIDB-09: Negative UI - Searching non-existent employee creates no DB changes', async ({ page }) => {
        await openUpdateTab(page);

        const conn = await getDbConnection();
        const [initialCount] = await conn.query('SELECT COUNT(*) as cnt FROM user_role');

        const input = employeeSearch(page);
        await input.click();
        await input.fill(`FakeUser_${Date.now()}`);
        await page.waitForTimeout(500);

        // Autocomplete should have 0 suggestions
        await expect(page.locator('#ac div')).toHaveCount(0);
        await expect(updateButton(page)).toBeDisabled();

        // Verify DB count has not changed
        const [afterCount] = await conn.query('SELECT COUNT(*) as cnt FROM user_role');
        expect(afterCount[0].cnt).toBe(initialCount[0].cnt);
    });

    test('UIDB-10: Approvers list verification against MySQL Admin and Executive Leadership roles', async ({ request }) => {
        const conn = await getDbConnection();
        const [dbApprovers] = await conn.query(`
            SELECT DISTINCT ur.USER_NAME, ur.ROLE_NAME
            FROM user_role ur
            WHERE ur.ROLE_NAME IN ('Admin', 'Executive Leadership')
        `);
        const dbApproverUsernames = dbApprovers.map(a => a.USER_NAME);

        // Query backend /get-approvers-list API
        const res = await request.get(`${BASE_URL.replace(/:\d+$/, ':8080')}/get-approvers-list`);
        if (res.status() === 200) {
            const apiApprovers = await res.json();
            for (const app of apiApprovers) {
                expect(
                    dbApproverUsernames,
                    `Approver "${app.userName}" must have Admin or Executive Leadership role in MySQL`
                ).toContain(app.userName);
            }
        }
    });
});
