const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const projectRoot = path.resolve(__dirname, '..');

const reportsDir = path.join(projectRoot, 'reports');
const historyDir = path.join(reportsDir, 'history');

const today = new Date().toISOString().split('T')[0];
const todayDir = path.join(historyDir, today);

console.log('========================================');
console.log(' SmartTracker Daily Automation');
console.log(` Date: ${today}`);
console.log('========================================');

fs.mkdirSync(todayDir, { recursive: true });

let exitCode = 0;

try {
    console.log('\nRunning Playwright tests...\n');

    // Runs the complete Playwright test suite
    // from tests/ including:
    // API, db&ui, exports, login, practices
    execSync('npx playwright test', {
        cwd: projectRoot,
        stdio: 'inherit',
    });

} catch (error) {
    exitCode = error.status || 1;

    console.log('\nPlaywright completed with test failures.');
    console.log(`Exit code: ${exitCode}`);
}

// Latest JSON report generated by Playwright
const latestResults = path.join(
    reportsDir,
    'latest-results.json'
);

// Today's historical JSON report
const historicalResults = path.join(
    todayDir,
    'results.json'
);

if (fs.existsSync(latestResults)) {

    fs.copyFileSync(
        latestResults,
        historicalResults
    );

    console.log(
        `\nHistorical report saved:\n${historicalResults}`
    );

    // ========================================
    // Create Overall Playwright Summary
    // ========================================

    const resultsData = JSON.parse(
        fs.readFileSync(historicalResults, 'utf8')
    );

    const stats = resultsData.stats || {};

    const passedTests = stats.expected || 0;
    const failedTests = stats.unexpected || 0;
    const skippedTests = stats.skipped || 0;

    const totalTests =
        passedTests +
        failedTests +
        skippedTests;

    const durationMs = stats.duration || 0;

    const durationMinutes = Number(
        (durationMs / 60000).toFixed(2)
    );

    const overallStatus =
        failedTests > 0
            ? 'FAILED'
            : 'PASSED';

    const summary = {
        date: today,
        totalTests,
        passed: passedTests,
        failed: failedTests,
        skipped: skippedTests,
        durationMs,
        durationMinutes,
        status: overallStatus,
    };

    const summaryFile = path.join(
        todayDir,
        'summary.json'
    );

    fs.writeFileSync(
        summaryFile,
        JSON.stringify(summary, null, 2)
    );

    console.log('\n========================================');
    console.log(' Overall Playwright Test Summary');
    console.log('========================================');
    console.log(`Total Tests : ${totalTests}`);
    console.log(`Passed      : ${passedTests}`);
    console.log(`Failed      : ${failedTests}`);
    console.log(`Skipped     : ${skippedTests}`);
    console.log(`Duration    : ${durationMinutes} min`);
    console.log(`Status      : ${overallStatus}`);
    console.log('========================================');

    console.log(
        `\nSummary saved:\n${summaryFile}`
    );

} else {

    console.error(
        '\nERROR: latest-results.json was not found.'
    );

    exitCode = 1;
}

console.log('\n========================================');
console.log(' Daily automation completed');
console.log(` Exit code: ${exitCode}`);
console.log('========================================');

process.exit(exitCode);